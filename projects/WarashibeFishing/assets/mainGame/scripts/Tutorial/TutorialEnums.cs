/// <summary>
/// 説明窓をどこに出すか（配置モード）。
///
/// ミッション制になってからは、台詞の位置は原則「位置アンカーのアクタ」で決める
/// （<see cref="TutorialDialogue.anchorTarget"/>）。この列挙型は
/// <see cref="TutorialWindow"/> が内部で「いま画面固定か追従か」を覚えるために使う。
/// </summary>
public enum TutorialAnchorMode
{
    /// <summary>キャンバス座標の固定位置に出す（画面中央原点・Y 下向き・1 単位 1px）。</summary>
    ScreenFixed,

    /// <summary>対象アクタのワールド位置を画面へ射影し、その少し上に追従させる。</summary>
    AboveTarget,
}

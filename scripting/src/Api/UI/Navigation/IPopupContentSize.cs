namespace SEED.UI;

// ============================================================
//  IPopupContentSize.cs — 中央のポップアップ（Popup）の中身が「欲しい高さ」を知らせる約束（2026-10-02。lane3。docs/ui_navigation.md §3.6）
//
//  Text.Measure（W2-6c）がまだ無く、中身の全体の高さは中身のスクリプトがいちばんよく知っている（一覧の行の数・見出しの折り返し）。
//  中身の根の画面のスクリプト（UiScreen の派生）がこれを実装すると、札の高さを「この高さ ＋ 内側の余白 × 2」にする
//  （上限 ratio.popup_max_height を超えた分は中身が自分でスクロールする）。実装しなければ中身の根のレイアウトの高さを使う。
// ============================================================

/// <summary>中央のポップアップの中身が欲しい高さを知らせる約束。</summary>
public interface IPopupContentSize
{
    /// <summary>
    /// 中身を全部出すなら欲しい高さ（キャンバスの単位。札の内側の余白は含まない。まだ分からなければ 0 以下）。
    /// 分かるまで（と、分かってから札の大きさが 1 フレーム落ち着くまで）ポップアップは見せずに待つ（上限つき）。
    /// </summary>
    float PopupContentHeight { get; }
}

// ============================================================
//  thumbnail — モデルサムネイル（プロジェクトパネル用）の純粋ロジック
// ------------------------------------------------------------
//  役割:
//    エディタのプロジェクトパネルに並ぶ 3D モデル（.glb / .gltf / .obj）の
//    小さな絵を作るために必要な「GPU に触れない計算」をここへ集める。
//
//  なぜ actor_thumbnail と別モジュールなのか:
//    図鑑用のアクタサムネイル（`actor_thumbnail`）とは目的も入出力も違う。
//      - 図鑑     : .actor を撮る／出力先はエディタが指定／視点は真横・正面・真上
//      - モデル一覧: モデルファイルを撮る／出力先はキャッシュ規則で決まる／斜め上から
//    一方、撮影そのもの（隔離ワールド線へ読み込んで ID マスクで切り抜く）は
//    まったく同じでよいので、駆動側（`app/thumbnail_ops.rs`）は 1 つの状態機械を
//    共有し、違いだけをこのモジュールと `actor_thumbnail` が持ち分ける。
//
//  責務の分割:
//    - `cache_key`  : キャッシュの鍵とファイルパス（エディタ C# と規則を共有する）
//    - `request`    : 通信プロトコル（要求の書式・応答の書式）と待ち行列
//    - `view_basis` : 任意方向からのカメラ自動フィット（図鑑側からも使う一般形）
// ============================================================

pub mod cache_key;
pub mod request;
pub mod view_basis;

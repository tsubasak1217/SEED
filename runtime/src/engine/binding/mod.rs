// ============================================================
//  binding/ — シーン内コンポーネントの変数を「値の供給元」として公開する仕組み
//
//  ## 役割（単一責任）
//  「アクタ名 / スロット名 / 変数名」で指す 1 個のスカラーまたは 3 成分ベクタを、
//  シーンから**毎フレーム読み出す**ための最小の機構だけを持つ。
//  最初の消費者は水面シェーディングアセットの `@ref` パラメータ（Phase W8.3）だが、
//  「どこへ流し込むか」は一切知らない（＝マテリアル・パーティクル・UI など
//  他の消費者が後から同じ機構へ乗れる）。
//
//  ## 構成
//  - `catalog` … **エンジン組込コンポーネントの供給値の正典表**。
//                「どのコンポーネントのどの変数が、どの型で読めるか」を 1 つの表にする。
//                供給値を足すときに触るのは **表への 1 行追加と読み取りの 1 腕だけ**。
//  - `resolve` … 保存文字列 `"アクタ名|スロット名|変数名"` の解析と、
//                シーンからの実値の解決（組込 ＋ C# スクリプトの `[Bindable]` フィールド）。
//
//  ## 型は厳密一致
//  `f32` を要求する側へ `vec3` の X 成分を渡すような**成分の部分取り出しは行わない**。
//  「なんとなく繋がる」ことを許すと、繋いだ本人にも何が流れているか分からなくなるため。
//
//  ## 解決に失敗したときの契約
//  アクタ／スロット／変数のいずれかが見つからない、型が合わない、スクリプトが
//  `[Bindable]` を外した ── いずれも **`None`** を返すだけで、エラーにも警告ログにもしない。
//  「バインドが切れている」ことは消費側がインスペクタで ⚠ 表示して伝える方が有用であり、
//  毎フレーム走る経路でログを吐くと実質使い物にならないため。
// ============================================================


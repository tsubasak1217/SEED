// ============================================================
//  terrain/brush_mask.rs — 地形ペイント系ブラシの「形状マスク」評価（純粋関数）
//
//  【責務】
//    地形編集ブラシ（レイヤペイント／カバー）の効き具合を 1 か所で決める。
//    ECS も GPU も IO も知らない。画像のデコードとキャッシュはエンジン層
//    （app/terrain_brush_mask_ops.rs）の責務であり、本ファイルは
//    「デコード済みのグレースケール（`CoverMask`）と幾何」から係数を返すだけである。
//
//  【なぜ 1 ファイルに集約したのか】
//    レイヤペイントブラシ（paint.rs）とカバーブラシ（cover/brush.rs）は
//    別々の場に作用するが、**縁の出方（形）は同じでなければならない**。
//    片方だけを直すと「同じ半径・同じ位置で塗ったのに効く範囲が違う」という
//    説明のつかない差が出る。形の規則をここ 1 本に閉じ込め、両者から呼ぶ。
//
//  【マスクの規約】
//    ・白（255）= フル強度、黒（0）= 0。R チャンネルだけを見る（`CoverMask::sample`）。
//    ・貼り付け先は **ブラシ球の XZ バウンディング正方形**
//      （中心 = 着弾点、一辺 = 2 × 半径）。回転は行わない（固定）。
//    ・正方形の外（UV が 0..1 の外）は `CoverMask::sample` が 0 を返すので効かない。
//
//  【マスク未指定・読み込み失敗のとき】
//    従来どおりの円形フォールオフ（`brush::falloff` の smoothstep）へ縮退する。
//    **読み込み失敗を「効果 0」にしない**のは安全側に倒すためである。
//    パスの打ち間違いや画像の破損でブラシが黙って無反応になると、
//    ユーザーは「地形編集が壊れた」としか分からず原因に辿り着けない。
//    形が円へ戻るだけなら「マスクが効いていない」と一目で分かる。
// ============================================================

use super::brush::falloff;
use super::cover::CoverMask;

// ─── 定数（マジックナンバー禁止）─────────────────────────────────────────────

/// マスク画像を貼り付ける正方形の一辺が、ブラシ半径の何倍か。
///
/// ブラシ球の XZ バウンディング正方形（＝直径ぶん）へ貼るので 2 倍である。
/// 「半径 r のブラシにマスクを指定したら、円に外接する正方形いっぱいに絵が乗る」
/// という対応にしておくと、円形フォールオフからマスクへ切り替えたときに
/// 効く範囲の広さが変わらない（絵の白い部分が円に収まっていれば見た目も揃う）。
const BRUSH_MASK_SQUARE_DIAMETER_FACTOR: f32 = 2.0;

/// UV の中心オフセット（正方形の中心を UV 0.5 に置くため）。
const BRUSH_MASK_UV_CENTER: f32 = 0.5;

// ============================================================
//  UV マッピング
// ============================================================

/// ワールド XZ を、ブラシのマスク正方形上の正規化 UV（0..1）へ写す。
///
/// - `center_xz`: ブラシ着弾点の XZ（正方形の中心）
/// - `radius`:    ブラシ半径（メートル）。正方形の一辺は 2 × radius。
/// - `world_xz`:  評価したいワールド座標の XZ
///
/// 規約（**これを唯一の定義とする**。他所で式を書き直さないこと）:
/// ```text
///   u = (world_x - center_x) / (2r) + 0.5
///   v = (world_z - center_z) / (2r) + 0.5
/// ```
///
/// 【V の向きを「+Z が V 増加（＝画像の上端が -Z 側）」にした理由】
///   カバーエミッタのマスク範囲（`CoverEmitRange::TextureMask` の `coverage_at`）が
///   まったく同じ式を使っており、「真上から見下ろした絵をそのまま地面へ貼る」
///   という向きになっている。地形ブラシだけ V を反転させると、同じ画像を
///   エミッタとブラシで使ったときに上下が食い違う。
///
///   轍スタンプ（`CoverStampShape::Texture`）は `v = 0.5 - forward/size` と
///   逆向きだが、あちらは **進行方向を画像の上端に合わせる**（回転する）
///   スタンプであり、「前が上」という別の規約に従っている。
///   本ブラシは回転しないので、回転しないエミッタ側と揃えるのが正しい。
///
/// 半径が 0 以下のときは UV を定義できないため、範囲外（-1, -1）を返す
/// （`CoverMask::sample` が 0 を返す ＝ 効かない）。
#[inline]
pub fn brush_mask_uv(center_xz: [f32; 2], radius: f32, world_xz: [f32; 2]) -> (f32, f32) {
    if !(radius > 0.0) {
        // 0..1 の外なら sample が 0 を返す。負値を返して「効かない」を明示する。
        return (-1.0, -1.0);
    }
    let side = radius * BRUSH_MASK_SQUARE_DIAMETER_FACTOR;
    let u = (world_xz[0] - center_xz[0]) / side + BRUSH_MASK_UV_CENTER;
    let v = (world_xz[1] - center_xz[1]) / side + BRUSH_MASK_UV_CENTER;
    (u, v)
}

// ============================================================
//  形状係数の評価
// ============================================================

/// ブラシ形状の係数（0..1）を返す。地形ブラシはすべてこの 1 本を通す。
///
/// - `mask`:          形状マスク。`None` ＝未指定。`Some` でも無効（読み込み失敗＝
///                    `CoverMask::empty()`）なら円形フォールオフへ縮退する。
/// - `center_xz`:     ブラシ着弾点の XZ
/// - `radius`:        ブラシ半径（メートル）
/// - `world_xz`:      評価したいワールド座標の XZ
/// - `fallback_dist`: 円形フォールオフに使う「中心からの距離」。
///                    カバーブラシは XZ 距離、密度・レイヤペイントブラシは
///                    3D 距離を渡す（**マスク未指定時の挙動を従来と 1 ビットも
///                    変えない**ため、呼び出し側が元々使っていた距離をそのまま渡す）。
///
/// 【マスク指定時に `fallback_dist` を無視する理由】
///   マスクは「形そのもの」を与えるものである。円形フォールオフを掛け合わせると
///   四隅が必ず削られ、正方形いっぱいの絵（板・矩形スタンプ）が作れなくなる。
///   白 = フル強度という約束を守るため、マスクがあれば置き換える。
#[inline]
pub fn brush_shape_factor(
    mask: Option<&CoverMask>,
    center_xz: [f32; 2],
    radius: f32,
    world_xz: [f32; 2],
    fallback_dist: f32,
) -> f32 {
    match mask {
        // ─── マスクあり: 正方形へ投影して画像を読む ───
        Some(m) if m.is_valid() => {
            let (u, v) = brush_mask_uv(center_xz, radius, world_xz);
            m.sample(u, v)
        }
        // ─── マスク未指定 / 無効: 従来どおりの円形 smoothstep ───
        //   `falloff` は密度ブラシ・レイヤペイントブラシが元々使っている関数そのもの。
        //   カバーブラシの旧実装（`t * t * (3 - 2t)`）とも式・境界条件が一致する。
        _ => falloff(fallback_dist, radius),
    }
}

/// マスクが「実際に形として効く」状態か（＝指定されていて、かつ有効か）。
///
/// 呼び出し側は、この判定で **サンプルの棄却範囲**（円か正方形か）を切り替える。
/// マスクは正方形いっぱいに貼るため、球の外側にある四隅も評価対象に含める必要がある。
#[inline]
pub fn brush_mask_is_active(mask: Option<&CoverMask>) -> bool {
    mask.is_some_and(|m| m.is_valid())
}

/// <summary>
/// 締め演出（<see cref="CutsceneMission"/>）のカメラ制御【カメラの主導権の選択キー】。
///
/// 保存形式はメンバ名の文字列なので、並べ替えても既存データの意味は変わらない。
/// 既定（宣言順の先頭）は <see cref="FollowNormal"/>＝カメラを触らない安全側。
/// </summary>
public enum CutsceneCameraMode
{
    /// <summary>
    /// 通常の追従（CameraMove）のまま。演出はカメラに<b>一切触らない</b>
    /// （位置・回転・画角のいずれも書かず、<see cref="TutorialRules.CameraSuspended"/> も立てない）。
    ///
    /// プレイヤー視点のまま画面の奥で怪獣が跳ねる絵になる。画角の指定も無効になる
    /// （CameraMove が毎フレーム画角を書いているので、ここで書くと奪い合いになるため）。
    /// </summary>
    FollowNormal,

    /// <summary>
    /// 怪獣のまわりを「距離・高さ・方位角」で回り込んだ位置から注視する（従来の演出）。
    /// 演出の間だけ通常の追従を止める。
    /// </summary>
    Orbit,

    /// <summary>
    /// カメラ目標アクタの位置・回転（＋そのアクタに Camera があれば画角）へ寄る。
    /// 会話カメラ（DialogueCameraDirector）と同じ流儀。目標アクタが未設定なら
    /// <see cref="Orbit"/> と同じ扱いへ落ちる。
    /// </summary>
    TargetActor,
}

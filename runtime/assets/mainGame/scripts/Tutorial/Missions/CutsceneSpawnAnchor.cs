/// <summary>
/// 締め演出（<see cref="CutsceneMission"/>）の出現位置の基準
/// 【跳ね始める場所の決め方の選択キー】。
///
/// 保存形式はメンバ名の文字列なので、並べ替えても既存データの意味は変わらない。
/// 既定（宣言順の先頭）は <see cref="CameraView"/>。
/// </summary>
public enum CutsceneSpawnAnchor
{
    /// <summary>
    /// 通常カメラの視界を基準に、画面の奥（海の上）へ出す。
    ///
    /// メインカメラの水平前方向へ「カメラからの距離」、真横へ「横ずれ」だけ進んだ点を
    /// 開始位置にし、高さは水面から「待機の深さ」だけ沈めた位置にする。
    /// カメラを動かさない演出（<see cref="CutsceneCameraMode.FollowNormal"/>）と組み合わせると、
    /// プレイヤー視点のまま画面の奥で怪獣が跳ねる絵になる。
    /// メインカメラが見つからないときは <see cref="TargetOrFloat"/> と同じ決め方へ落ちる。
    /// </summary>
    CameraView,

    /// <summary>
    /// 目標アクタ（あればその位置と向き）、無ければウキの沖側を基準にする（従来の決め方）。
    /// 演出の場所をシーン上のアクタで固定したいときに使う。
    /// </summary>
    TargetOrFloat,
}

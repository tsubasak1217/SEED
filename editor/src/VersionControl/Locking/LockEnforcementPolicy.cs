// ============================================================
//  LockEnforcementPolicy.cs — ロックをどこまで強制するか
//
//  【役割】
//  「他の人がロックしているファイルへの書き込みを止めるか、注意だけにするか」
//  という 1 つの方針を表す。判定表（<see cref="LockGatePolicy"/>）と
//  設定ファイル（<see cref="LockGateSettings"/>）の両方が同じ語彙を使う。
//
//  【なぜ切り替えられるようにするのか】
//  ロックの強制は「他の人の作業を止める」機能でもある。サーバや認証の
//  不調で誤って止めてしまったとき、利用者が自分で逃げ道を作れないと
//  作業そのものが止まる。設定 1 つで「注意のみ」へ落とせるようにしておく。
//  既定は <see cref="Enforce"/>（止める）。逃げ道は明示的に選ぶもの。
//
//  【依存】
//  WPF にも LoreVcs にも依存しない（単体テストへそのままリンクできる）。
// ============================================================

namespace SEEDEditor.VersionControl.Locking;

/// <summary>
/// ロックの強制方針。
/// </summary>
public enum LockEnforcementPolicy
{
    /// <summary>
    /// 他の人がロックしているファイルへの書き込みを止める（既定）。
    /// </summary>
    Enforce = 0,

    /// <summary>
    /// 止めずに注意だけ出す。ロックの表示は今までどおり行う。
    /// </summary>
    WarnOnly = 1,
}
